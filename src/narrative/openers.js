export const openerIds = Object.keys(OPENERS);
export function openerLines(id) { return OPENERS[id] ?? []; }
// 첫 줄 고르기는 게임의 주사위를 쓰지 않는다: 줄 하나 고르는 일로 뒤따르는 사건 운이 바뀌지 않게 (씨앗 하나로 도는 점검이 흔들렸다)
export function opener(g, id, _rng) {
  const pool = OPENERS[id];
  if (!pool) return '';
  const n = (g.openerN = ((g.openerN ?? 0) + 1) % 100000);
  let h = 2166136261;
  for (const ch of `${id}:${g.seed ?? 0}:${g.date?.year}:${g.date?.month}:${n}`) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return pickLine(g, makeRng({ s: h | 0 }), pool) || pool[0];
}
