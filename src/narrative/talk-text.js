// 호감에 따른 마무리 한 줄
export function closeness(aff) {
  if (aff >= 70) return '이제는 말하지 않아도 편한 사이다.';
  if (aff >= 40) return '꽤 가까워졌다.';
  if (aff >= 10) return '조금 가까워졌다.';
  if (aff >= -20) return '아직은 서먹하다.';
  return '골이 깊다.';
}

