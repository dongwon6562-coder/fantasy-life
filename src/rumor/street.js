  const cal = (g.nature?.active ?? []).find((a) => (a.region && regionHas(a.region, pl)));
  if (cal) add(`cal_${cal.kind}`, 8, CAL_LINE[cal.kind]);
  const rising = (g.revolt?.risings ?? []).find((x) => x.place === pl && (x.phase === 'up' || x.phase === 'brewing'));
