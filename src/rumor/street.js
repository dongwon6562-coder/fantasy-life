export function weatherOf(year, month) {
  const k = year * 12 + month, w = hash(k, 91), r = hash(k, 77);
  const tod = r < 0.48 ? 'day' : r < 0.68 ? 'dusk' : r < 0.82 ? 'dawn' : 'night';
  const s = [0, 'w', 'w', 'sp', 'sp', 'sp', 'su', 'su', 'su', 'au', 'au', 'au', 'w'][month];
  let x = 'clear';
  if (s === 'w') x = w < 0.11 ? 'blizzard' : w < 0.45 ? 'snow' : w < 0.62 ? 'cloudy' : w < 0.72 ? 'wind' : 'clear';
  else if (s === 'sp') x = w < 0.21 ? 'rain' : w < 0.26 ? 'storm' : w < 0.39 ? 'cloudy' : w < 0.49 ? 'fog' : w < 0.61 ? 'wind' : 'clear';
  else if (month === 7) x = w < 0.34 ? 'rain' : w < 0.46 ? 'storm' : w < 0.56 ? 'cloudy' : w < 0.62 ? 'wind' : 'clear';
  else if (s === 'su') x = w < 0.11 ? 'rain' : w < 0.21 ? 'storm' : w < 0.29 ? 'cloudy' : w < 0.35 ? 'wind' : 'clear';
  else x = w < 0.21 ? 'rain' : w < 0.27 ? 'storm' : w < 0.42 ? 'fog' : w < 0.56 ? 'cloudy' : w < 0.72 ? 'wind' : 'clear';
  if (x === 'fog' && tod === 'night') x = 'cloudy';
  return x;
}
