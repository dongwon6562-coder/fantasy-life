/** 이달 거리 풍경 하나 고르기: 무게대로, 최근에 쓴 것은 피한다 */
export function streetPick(g, rng, pl, recent = []) {
  let c = streetCandidates(g, pl);
  const fresh = c.filter((x) => !recent.includes(x.key));
  if (fresh.length) c = fresh;
  const sum = c.reduce((a, x) => a + x.w, 0);
  let t = rng.float(0, sum);
  for (const x of c) { t -= x.w; if (t <= 0) return x; }
  return c[c.length - 1] ?? { key: 'none', text: `${J(PLACES[pl]?.name ?? '고장', '은/는')} 오늘도 그대로다.` };
}
