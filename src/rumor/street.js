  const r = g.realm, m = g.date.month, season = SEASON_OF(m), out = [];
  const add = (key, w, text) => { if (text) out.push({ key, w, text }); };
  const leonia = realmAt(pl) === 'leonia', town = isTown(pl);
  const R = g.rumor ?? {};
  // 세상 형편
  if (r && leonia && !r.king?.alive && mi(g) - (R.mourn ?? -99) < 4) add('mourn', 12, town ? '사람들 팔에 검은 천이 감겨 있다. 국상 중이라 장터 악사들도 입을 다물었다.' : '예배당 종이 날마다 울린다. 국상이라 혼례를 미룬 집이 둘이다.');
